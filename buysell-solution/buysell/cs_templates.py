def list_templates() -> dict:
    return {k: v["name"] for k, v in TEMPLATES.items()}


def render(template_key: str, product_name: str = "", buyer: str = "",
           order_id: str = "") -> str:
    tpl = TEMPLATES[template_key]
    text = tpl["body"]
    text = text.replace("{상품명}", product_name or "상품")
    text = text.replace("{고객명}", buyer)
    text = text.replace("{주문번호}", order_id)
    return text
